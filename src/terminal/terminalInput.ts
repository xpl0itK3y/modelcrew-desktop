// Что именно панель отправляет в PTY: клавиатура пользователя или отчёты мыши.
//
// Оба потока идут одним каналом `onData`. TUI-агенты включают трекинг мыши
// (`CSI ?1002h` / `?1003h`), и тогда терминал шлёт координаты на каждое
// движение курсора над панелью — десятки сообщений в секунду. Отличить их от
// набора текста нужно, чтобы «пользователь работает в этой панели» не
// срабатывало от того, что мышь просто прошла мимо.

// SGR (`CSI < b ; x ; y M|m`) — то, что включают современные приложения:
// координаты не ограничены 223 колонками.
const SGR_MOUSE = /^\x1b\[<\d+;\d+;\d+[Mm]$/;
// urxvt (`CSI b ; x ; y M`) — встречается у старых сборок.
const URXVT_MOUSE = /^\x1b\[\d+;\d+;\d+M$/;
// X10/normal (`CSI M b x y`) — байты координат идут сырыми, без разделителей.
const X10_MOUSE = /^\x1b\[M/;

// Отчёт мыши: нажатие, отпускание, колесо или движение курсора.
export function isMouseReport(data: string): boolean {
  return (
    SGR_MOUSE.test(data) || URXVT_MOUSE.test(data) || X10_MOUSE.test(data)
  );
}
