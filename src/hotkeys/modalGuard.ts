// Модальное окно поверх сетки: настройки, подтверждение, вход в GitHub,
// ошибка git. Пока такое открыто, сетка не отвечает ни на горячие клавиши,
// ни на ⌘-перетаскивание.
//
// Спрашивать приходится у документа, а не у самого диалога: оба слушателя
// висят на window в фазе перехвата, то есть получают событие раньше, чем оно
// вообще доходит до диалога, — остановить его изнутри нечем. И ⌘-перетаскивание
// вдобавок ищет панель по координатам курсора, не глядя, что лежит сверху:
// затемнение поверх терминалов его не останавливало совсем.
//
// Всплывающие окна, которые ничего не перекрывают (оповещение об обновлении),
// помечены aria-modal="false" и сюда не попадают.
export function isCoveredByModal(): boolean {
  return document.querySelector('[aria-modal="true"]') !== null;
}
