// ⌘W у сетки значит «закрыть терминал». Но у колонки редактора свои вкладки,
// и человек, набирающий текст в файле, нажимает ⌘W, чтобы закрыть файл, — как
// в любом редакторе. Сетка слушает клавиши раньше всех, в фазе перехвата на
// window, и забирала это нажатие себе: закрывался активный терминал, а с ним и
// агент, который в нём работал.
//
// Поэтому место со своими вкладками помечает себя атрибутом, и сетка, увидев
// фокус внутри такого места, ⌘W пропускает дальше — туда, где его ждут.

export const OWN_CLOSE_KEY = "data-own-close-key";

/// Фокус стоит там, где ⌘W закрывает своё, а не терминал.
export function closesItsOwn(target: EventTarget | null): boolean {
  return target instanceof Element && target.closest(`[${OWN_CLOSE_KEY}]`) !== null;
}
