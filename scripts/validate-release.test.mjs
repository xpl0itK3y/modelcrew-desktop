test("release notes containing markup are rejected", () => {
  // Заметки попадают в окно обновления, поэтому угловые скобки в них не
  // проезжают дальше этой проверки.
  const notes = releaseNotes(VERSION);
  notes.en.highlights = ["<img src=x onerror=alert(1)>"];

  expectFailure(runFixture({ notes }), /cannot contain HTML brackets/u);
});

