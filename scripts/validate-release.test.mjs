test("object-src with a wildcard is rejected", () => {
  expectFailure(
    runFixture({
      security: { csp: "default-src 'self'; script-src 'self'; object-src *" },
    }),
    /csp object-src must not allow \*/u,
  );
});

test("a csp without default-src is rejected", () => {
  expectFailure(
    runFixture({
      security: { csp: "script-src 'self'; object-src 'none'; base-uri 'self'" },
    }),
    /csp must set default-src/u,
  );
});

test("'unsafe-inline' limited to style-src still passes", () => {
  // Осознанное послабление: инлайновые стили нужны интерфейсу, инлайновые
  // скрипты — нет. Тест держит границу, чтобы правило не «починили» в
  // ложную тревогу и не начали её обходить.
  const result = runFixture({
    security: {
      csp: "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; object-src 'none'",
    },
  });

  expectSuccess(result);
  assert.match(shippedCsp, /style-src[^;]*'unsafe-inline'/u);
  assert.doesNotMatch(shippedCsp, /script-src[^;]*'unsafe-(?:inline|eval)'/u);
});

test("the shipped policy passes the gate that protects it", () => {
  expectSuccess(runFixture({ security: { csp: shippedCsp } }));
});

test("a dev-only policy with 'unsafe-eval' does not block a release", () => {
  // Проверяется только выпускаемая политика: devCsp нужен HMR и наружу не
  // уезжает. Закрепляем границу, чтобы её не перепутали в обе стороны.
  const result = runFixture({
    security: {
      csp: shippedCsp,
      devCsp: "default-src 'self'; script-src 'self' 'unsafe-inline' 'unsafe-eval'",
    },
  });

  expectSuccess(result);
  assert.match(shippedConfig.app.security.devCsp, /'unsafe-eval'/u);
});

test("an unparsable tauri.conf.json is rejected", () => {
  // Обрывок после конфликта слияния не должен читаться как «политика есть».
  const fixture = createFixture();
  fs.writeFileSync(path.join(fixture, "src-tauri", "tauri.conf.json"), '{ "app": { "security": ');

  expectFailure(run(fixture), /Cannot read JSON/u);
});

