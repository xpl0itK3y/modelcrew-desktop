test("a placeholder in a neighbouring section does not block the release", () => {
  const changelogText = `# Changelog\n\n## ${VERSION}\n\n### Русский\n\nРелиз.\n\n### English\n\nRelease.\n\n## 0.0.1\n\nTODO\n`;

  expectSuccess(runFixture({ changelogText }));
});

// Валидатор релиза не смотрит на plugins.updater, поэтому подменённый адрес
// манифеста или чужой публичный ключ прошли бы шлюз незамеченными. Пока этой
// проверки нет в скрипте, значения закреплены здесь.
test("the shipped updater stays pinned to https endpoints and the release key", () => {
  const updater = shippedConfig.plugins.updater;

  assert.ok(Array.isArray(updater.endpoints) && updater.endpoints.length > 0);
  for (const endpoint of updater.endpoints) {
    assert.match(endpoint, /^https:\/\//u, `updater endpoint is not https: ${endpoint}`);
  }
  assert.equal(
    updater.pubkey,
    "dW50cnVzdGVkIGNvbW1lbnQ6IG1pbmlzaWduIHB1YmxpYyBrZXk6IEFENUE2NDg4RjA1NjJDMjIKUldRaUxGYndpR1JhcmViU1V5M1hGVVpUelZydGp2R3F5aWV0Qkh0YU8yTEVTVnlRNGxGZjBOU0sK",
  );
});
